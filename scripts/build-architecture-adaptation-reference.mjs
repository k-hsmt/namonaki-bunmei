/**
 * Issue #35 D2-a: builds the fixed world-wide reference distribution for regional adaptation inputs
 * (architecture-adaptation-reference-v1). Seeds 1001–1200 are used so that the 200-seed audit
 * (seeds 1–200) is measured out of sample. Output is a frozen TypeScript table; regenerate only with
 * Human review because it changes every tradition.
 *   npm run build && node scripts/build-architecture-adaptation-reference.mjs > src/architecture/adaptation-reference-v1.ts
 */
import {generateWorldPrototype} from '../dist/terrain/world-prototype.js';
import {captureTerrainRecord} from '../dist/terrain/capture-terrain-record.js';
import {captureRiverReaches} from '../dist/terrain/river-reaches-review.js';
import {createGeneratedBridgeReview} from '../dist/story/generated-bridge-review.js';
import {createInitialVegetation} from '../dist/vegetation/initial-v1.js';
import {readOwnedRecordPhysics} from '../dist/terrain/owned-record-physics.js';
import {measureSiteAdaptation} from '../dist/architecture/adaptation-v1.js';

const FIRST=1001,COUNT=200,sites=['river-bank','hill-side','coast-inlet'],keys=['slope','water','rock','forest'];
const values=Object.fromEntries(keys.map(k=>[k,[]]));
let used=0;
for(let seed=FIRST;used<COUNT;seed++){
 const result=generateWorldPrototype(seed);if(result.status!=='ok')continue;
 const terrain=captureTerrainRecord(result.world,'world-terrain-v1');
 const review=createGeneratedBridgeReview(terrain,captureRiverReaches(terrain),'field-only','organic-v3');
 if(review.status!=='review-only')continue;
 used++;
 const vegetation=createInitialVegetation(review.review);
 for(const site of sites){const m=measureSiteAdaptation(readOwnedRecordPhysics(terrain.sites[site].physics),vegetation.initial[site]);for(const k of keys)values[k].push(m[k]);}
}
const quantiles=xs=>{const s=[...xs].sort((a,b)=>a-b);return Array.from({length:101},(_,q)=>s[Math.min(s.length-1,Math.floor(q*(s.length-1)/100))]);};
const table=Object.fromEntries(keys.map(k=>[k,quantiles(values[k])]));
console.log(`/**
 * Issue #35 D2-a: world-wide reference distribution of year-0 site adaptation inputs
 * (architecture-adaptation-reference-v1). Generated by scripts/build-architecture-adaptation-reference.mjs
 * from seeds ${FIRST}–${FIRST+COUNT-1} (${COUNT} worlds × 3 sites). 101 quantiles (0..100%) per input, per-mille values.
 * Frozen data: changing it changes every tradition, so regenerate only with Human review.
 */
export const ADAPTATION_REFERENCE_ID='architecture-adaptation-reference-v1';
export const adaptationReference:Readonly<Record<'slope'|'water'|'rock'|'forest',readonly number[]>>=Object.freeze({
${keys.map(k=>` ${k}:Object.freeze([${table[k].join(',')}]),`).join('\n')}
});`);
